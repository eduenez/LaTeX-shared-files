#!/usr/bin/env python3
"""gen_manifest.py — regenerate toolkit/MANIFEST.tsv from the files under toolkit/ (run from LaTeX-shared-files after adding or
removing a toolkit file; commit the result). Rules: scripts/* -> _scripts/*, templates/* -> _templates/* and docs/{STYLE,ONBOARDING,
CONVERTING}.md are managed and used in place by submodule repositories; root/Makefile and root/latexmkrc are managed and replaced by a stub
in submodule repositories; the other root/* files are managed (vendored) / seed (submodule); root/.gitignore and docs/AGENTS.md are seeds."""
import os, sys
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
rows = []


def walk(src, dest, mode, sub, skip=()):
    for r, ds, fs in os.walk(src):
        ds[:] = sorted(d for d in ds if d != '__pycache__')
        for f in sorted(fs):
            if f.endswith('.pyc') or f == '.DS_Store':
                continue
            p = os.path.join(r, f)
            rel = os.path.relpath(p, src)
            if rel not in skip:
                rows.append((mode, p, os.path.normpath(os.path.join(dest, rel)), sub))


walk('scripts', '_scripts', 'managed', 'use', skip=('gen_manifest.py',))  # maintainer-only tool stays here
walk('templates', '_templates', 'managed', 'use')
rows.append(('managed', 'root/Makefile', 'Makefile', 'stub'))
rows.append(('managed', 'root/latexmkrc', 'latexmkrc', 'stub'))
walk('root', '.', 'managed', 'seed', skip=('Makefile', 'latexmkrc', '.gitignore'))
rows.append(('seed', 'root/.gitignore', '.gitignore', 'seed'))
for f in ('STYLE.md', 'ONBOARDING.md', 'CONVERTING.md'):
    rows.append(('managed', 'docs/' + f, f, 'use'))
rows.append(('seed', 'docs/AGENTS.md', 'AGENTS.md', 'seed'))
head = ("# mode\tsource (in toolkit/)\tdestination (in a consuming repository)\tsubmodule\n"
        "# mode managed = a vendored, pristine, checksummed copy (_scripts/vendor.lock), refreshed by `make update-shared`, never edited in the consumer\n"
        "# mode seed    = copied once when missing; the consumer owns it afterwards\n"
        "# submodule = what a repository does that has LaTeX-shared-files as a submodule at _packages/: use = read in place (nothing copied);\n"
        "#             seed = copied once; stub = a small file that includes the toolkit's is written instead\n"
        "# (generated by scripts/gen_manifest.py — do not edit by hand)\n")
open('MANIFEST.tsv', 'w').write(head + ''.join(f'{m}\t{s}\t{d}\t{u}\n' for m, s, d, u in rows))
print(f'MANIFEST.tsv: {len(rows)} entries', file=sys.stderr)
